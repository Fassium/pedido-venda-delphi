-- Banco do Pedido de Venda, Firebird 3.0 ou mais novo
-- Rodar num banco vazio, com dialeto 3 e charset UTF8, em modo auto-commit
--
-- Criar o banco vazio (a pasta C:\PedidoVenda precisa existir), no PowerShell:
--   & "C:\Program Files\Firebird\Firebird_5_0\isql.exe" -user SYSDBA -password SUA_SENHA
-- e no prompt SQL> do isql:
--   CREATE DATABASE 'localhost:C:\PedidoVenda\PEDIDO_VENDA.FDB' PAGE_SIZE 16384 DEFAULT CHARACTER SET UTF8;
--   quit;

-- Tabelas sem dependencia

CREATE TABLE CLIENTE (
  CODIGO  INTEGER      NOT NULL,
  NOME    VARCHAR(100) NOT NULL,
  CIDADE  VARCHAR(60)  NOT NULL,
  UF      CHAR(2)      NOT NULL,
  CONSTRAINT PK_CLIENTE PRIMARY KEY (CODIGO)
);

CREATE TABLE PRODUTO (
  CODIGO       INTEGER       NOT NULL,
  DESCRICAO    VARCHAR(100)  NOT NULL,
  PRECO_VENDA  NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_PRODUTO PRIMARY KEY (CODIGO),
  CONSTRAINT CK_PRODUTO_PRECO_VENDA CHECK (PRECO_VENDA >= 0)
);

-- Pedido: o número vem da sequence (NEXT VALUE FOR no INSERT, devolvido com RETURNING)

CREATE SEQUENCE SEQ_PEDIDO_NUMERO;

CREATE TABLE PEDIDO (
  NUMERO_PEDIDO   BIGINT        NOT NULL,
  DATA_EMISSAO    DATE          NOT NULL,
  CODIGO_CLIENTE  INTEGER       NOT NULL,
  VALOR_TOTAL     NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_PEDIDO PRIMARY KEY (NUMERO_PEDIDO),
  CONSTRAINT FK_PEDIDO_CLIENTE FOREIGN KEY (CODIGO_CLIENTE)
    REFERENCES CLIENTE (CODIGO)
    USING INDEX IDX_PEDIDO_CODIGO_CLIENTE,
  CONSTRAINT CK_PEDIDO_VALOR_TOTAL CHECK (VALOR_TOTAL >= 0)
);

-- Itens: o ID é gerado pelo banco (IDENTITY)

CREATE TABLE PEDIDO_ITEM (
  ID              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  NUMERO_PEDIDO   BIGINT        NOT NULL,
  CODIGO_PRODUTO  INTEGER       NOT NULL,
  QUANTIDADE      INTEGER       NOT NULL,
  VLR_UNITARIO    NUMERIC(15,2) NOT NULL,
  VLR_TOTAL       NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_PEDIDO_ITEM PRIMARY KEY (ID),
  CONSTRAINT FK_PEDIDO_ITEM_PEDIDO FOREIGN KEY (NUMERO_PEDIDO)
    REFERENCES PEDIDO (NUMERO_PEDIDO)
    USING INDEX IDX_PEDIDO_ITEM_NUMERO_PEDIDO,
  CONSTRAINT FK_PEDIDO_ITEM_PRODUTO FOREIGN KEY (CODIGO_PRODUTO)
    REFERENCES PRODUTO (CODIGO)
    USING INDEX IDX_PEDIDO_ITEM_CODIGO_PRODUTO,
  CONSTRAINT CK_PEDIDO_ITEM_QUANTIDADE CHECK (QUANTIDADE > 0),
  CONSTRAINT CK_PEDIDO_ITEM_VLR_UNITARIO CHECK (VLR_UNITARIO >= 0),
  CONSTRAINT CK_PEDIDO_ITEM_VLR_TOTAL CHECK (VLR_TOTAL = QUANTIDADE * VLR_UNITARIO)
);

